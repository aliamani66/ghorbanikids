        var GkTestsEngine = {
            tests: GK_TESTS_RAW,
            currentQuiz: null,
            currentQIndex: 0,
            userAnswers: {},
            shuffledQuestions: [],

            shuffleArray: function(array) {
                var arr = array.slice();
                for (var i = arr.length - 1; i > 0; i--) {
                    var j = Math.floor(Math.random() * (i + 1));
                    var temp = arr[i];
                    arr[i] = arr[j];
                    arr[j] = temp;
                }
                return arr;
            },

            startQuiz: function(quizId) {
                var quiz = this.tests.find(function(t) { return t.id === quizId; });
                if (!quiz) return;

                this.currentQuiz = quiz;
                this.currentQIndex = 0;
                this.userAnswers = {};

                // Shuffle questions and options according to Rule 11
                var self = this;
                this.shuffledQuestions = this.shuffleArray(quiz.questions).map(function(q) {
                    var optsWithIndex = q.opts.map(function(optText, idx) {
                        return { text: optText, isCorrect: (idx === q.ans) };
                    });
                    var shuffledOpts = self.shuffleArray(optsWithIndex);
                    return {
                        q: q.q,
                        topic: q.topic,
                        options: shuffledOpts
                    };
                });

                document.getElementById('gkQuizTitle').textContent = quiz.title;
                document.getElementById('gkQuizFooter').style.display = 'flex';
                document.getElementById('gkQuizPlayerModal').classList.add('is-active');
                document.body.style.overflow = 'hidden';

                this.renderQuestion();
            },

            closeQuiz: function() {
