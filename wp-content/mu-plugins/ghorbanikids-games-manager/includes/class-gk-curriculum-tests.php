        public function ajax_submit_test_score() {
        global $wpdb;
        $st_token = sanitize_text_field($_POST['st_token'] ?? '');
        $quiz_id = sanitize_text_field($_POST['quiz_id'] ?? '');
        $quiz_title = sanitize_text_field($_POST['quiz_title'] ?? '');
        $score = intval($_POST['score'] ?? 0);
        $level_text = sanitize_text_field($_POST['level'] ?? '');
        $topics_json = sanitize_text_field($_POST['topics'] ?? '{}');

        if (empty($quiz_id)) {
            wp_send_json_error(['message' => 'اطلاعات آزمون ناقص است.']);
        }

        $student_id = 0;
        $class_id = 0;
        $org_id = 0;

        if (!empty($st_token)) {
            $student = $wpdb->get_row($wpdb->prepare(
                "SELECT * FROM {$wpdb->prefix}gk_students WHERE student_token = %s",
                $st_token
            ));
            if ($student) {
                $student_id = $student->id;
                $class_id = $student->class_id;
                $org_id = $student->org_id;

                // Update total game/test score on student profile
                $wpdb->query($wpdb->prepare(
                    "UPDATE {$wpdb->prefix}gk_students SET total_game_score = total_game_score + %d WHERE id = %d",
                    $score,
                    $student->id
                ));
            }
        }

